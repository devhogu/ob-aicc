# Names that keep their capital letter: bodies of the Bank, the Bank, document titles.
PROTECT = [
    r'Совет[а-яё]{0,3} директоров', r'Комитет[а-яё]{0,3} Совета директоров', r'Правлени[а-яё]{1,3} Банка',
    r'Управляющ[а-яё]{2,3} комитет[а-яё]{0,3} по AI', r'Банк[а-яё]{0,3}',
    r'Положени[а-яё]{1,3} об AICC', r'Бизнес-модел[а-яё]{1,3}', r'Операционн[а-яё]{2,3} модел[а-яё]{1,3}',
    r'Модел[а-яё]{1,3} управления портфелем', r'Модел[а-яё]{1,3} жизненного цикла решений',
    r'Политик[а-яё]{1,3} применения AI', r'Терминологи[а-яё]{1,3} и стил[а-яё]{1,3}',
    r'Заявлени[а-яё]{1,3} о намерениях(?: по внедрению AI)?', r'Каталог[а-яё]{0,3} документов',
    r'Общ[а-яё]{2,3} делов[а-яё]{2,3} и технологическ[а-яё]{2,3} терминологи[а-яё]{1,3}',
    r'«(?:[^»\s]+\s?){1,5}»',  # short quotations (titles, state names) keep their own spelling
]
START = re.compile(r'(?:^|[.!?]\s+|[|#>\[(«:]\s*|^\s*(?:[-*]|\d+(?:\.\d+)*\.)\s+|—\s+(?=[А-ЯЁ][а-яё]+:))$')


def stem(word):
    if not re.match(r'[А-ЯЁ]', word):
        return re.escape(word)
    base = re.sub(r'(?:ая|ое|ые|ый|ий|ой|ия|ие|ья|ье)$', '', word) if len(word) > 5 else word
    base = re.sub(r'[аяеёиоуыьйюэ]$', '', base)
    return re.escape(base) + r'[а-яё]{0,4}'


def pattern():
    alts = []
    for term in sorted(set(VOCAB_TERMS), key=len, reverse=True):
        words = term.split()
        alts.append(r'\s+'.join(stem(w) if re.match(r'[А-ЯЁ]', w) else (re.escape(w[:-2]) + r'[а-яё]{0,4}' if re.match(r'[а-яё]{5,}', w) else re.escape(w)) for w in words))
    return re.compile(r'(?<![А-Яа-яЁё\w-])(?:' + '|'.join(alts) + r')(?![А-Яа-яЁё\w-])')


TERM = pattern()


def lower_words(text):
    return re.sub(r'(?<![\w-])([А-ЯЁ])(?=[а-яё])', lambda m: m.group(1).lower(), text)


def convert(text):
    out, pos = [], 0
    fence = False
    for line in text.splitlines(keepends=True):
        if line.startswith('```'):
            fence = not fence
        if fence or line.startswith('```'):
            out.append(line)
            continue
        masked = line
        holes = []
        for pat in PROTECT:
            masked = re.sub(pat, lambda m: holes.append(m.group(0)) or '\x00%d\x00' % (len(holes) - 1), masked)

        def repl(m):
            before = masked[:m.start()]
            if START.search(before) or not before.strip():
                return m.group(0)
            return lower_words(m.group(0))
        masked = TERM.sub(repl, masked)
        while '\x00' in masked:
            masked = re.sub(r'\x00(\d+)\x00', lambda m: holes[int(m.group(1))], masked)
        out.append(masked)
    return ''.join(out)


if __name__ == '__main__':
    dry = '--dry' in sys.argv
    for name in [a for a in sys.argv[1:] if a != '--dry']:
        path = Path(name)
        old = path.read_text(encoding='utf-8')
        new = convert(old)
        if dry:
            sys.stdout.write(new)
        elif new != old:
            path.write_text(new, encoding='utf-8')
